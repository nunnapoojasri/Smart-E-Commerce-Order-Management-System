"""Streamlit interface for the CrewAI order management workflow."""

import os

import streamlit as st

from order_management.data import assess_escalation, get_order
from order_management.local_resolution import resolve_locally


st.set_page_config(page_title="Order Support", page_icon="📦")
st.title("Smart E-Commerce Order Support")
api_key_configured = bool(os.getenv("OPENAI_API_KEY"))
if api_key_configured:
    st.caption("CrewAI mode: responses are generated by the configured language model.")
else:
    st.info(
        "Local mode: no API key is needed. Responses use the bundled sample order, "
        "inventory, and tracking data."
    )
st.write(
    "Enter your order ID and question. Your request will be checked against the "
    "available order, inventory, and tracking records."
)

with st.form("order_question"):
    order_id = st.text_input("Order ID", placeholder="ORD1025")
    customer_question = st.text_area(
        "How can we help?",
        placeholder="My order is late. Can you check its status?",
    )
    submitted = st.form_submit_button("Check my order")

if submitted:
    if not order_id.strip() or not customer_question.strip():
        st.error("Enter both an order ID and your question.")
    else:
        try:
            order = get_order(order_id)
            with st.spinner("Reviewing your order..."):
                if api_key_configured:
                    from order_management.crew import ResolutionOutput, build_order_crew

                    crew = build_order_crew()
                    result = crew.kickoff(
                        inputs={
                            "order_id": order["order_id"],
                            "customer_question": customer_question.strip(),
                        }
                    )
                    output = result.tasks_output[-1].pydantic
                    if not isinstance(output, ResolutionOutput):
                        raise RuntimeError(
                            "The Resolution Agent did not return a valid structured result."
                        )
                else:
                    output = resolve_locally(order["order_id"], customer_question.strip())

            required_escalation = assess_escalation(
                customer_question, order["tracking_status"]
            )
            escalated = output.escalated or required_escalation["required"]
            if escalated:
                reason = (
                    required_escalation["reason"]
                    if required_escalation["required"]
                    else output.escalation_reason
                )
                st.warning("This request needs help from a human support representative.")
                st.write(
                    "Your request has been flagged for human follow-up. "
                    "No refund, replacement, or other account change has been made."
                )
                if reason:
                    st.caption(f"Escalation reason: {reason.replace('_', ' ')}")
                if output.internal_summary:
                    st.subheader("Support handoff")
                    st.write(output.internal_summary)
            else:
                st.subheader("Response")
                st.write(output.customer_response)
        except LookupError as error:
            st.error(str(error))
        except Exception as error:
            st.error(f"Unable to process this request: {error}")
